x['期间']=np.where(x['D0选中日'].str[:4].le('2024'),'2022-24',x['D0选中日'].str[:4])
Y='D2开收跌停并集';Z='D2D3连续收盘跌停'
specs=[
 ('首板量<前5日均量','首板量除前5日均量','lt1'),
 ('首板量<前10日均量','首板量除前10日均量','lt1'),
 ('首板量<前20日均量','首板量除前20日均量','lt1'),
 ('首板量<前20日均量一半','首板量除前20日均量','lt05'),
 ('首板一字','首板一字','eq1'),
 ('二板缩量','二板缩量','eq1'),
 ('三板放量','三板放量','eq1'),
 ('四板放量','四板放量','eq1'),
 ('二缩三放','先缩后二板三板放量','eq1'),
 ('连板至少5天','已连板天数','ge5'),
 ('D0较前一板缩量','D0量除前一板量','lt1'),
]
rows=[]
for label,col,rule in specs:
    avail=x[col].notna()
    if rule=='lt1': mask=x[col]<1
    elif rule=='lt05': mask=x[col]<.5
    elif rule=='eq1': mask=x[col]==1
    elif rule=='ge5': mask=x[col]>=5
    else: raise ValueError(rule)
    for period in ['2022-24','2025','2026','全部']:
        base=avail & ((x['期间']==period) if period!='全部' else True)
        a=x[base & mask];b=x[base & ~mask]
        assert len(a)+len(b)==int(base.sum())
        def rate(frame,target):
            return 100*int(frame[target].sum())/len(frame) if len(frame) else np.nan
        rows.append({'特征':label,'期间':period,'可比较笔数':int(base.sum()),
            '特征成立笔数':len(a),'成立时D2跌停数':int(a[Y].sum()),'成立时D2跌停率_pct':rate(a,Y),
            '对照笔数':len(b),'对照D2跌停数':int(b[Y].sum()),'对照D2跌停率_pct':rate(b,Y),
            '成立时连续跌停数':int(a[Z].sum()),'对照连续跌停数':int(b[Z].sum())})
g=pd.DataFrame(rows)
g.to_csv(R/'量能假设_分期对照.csv',index=False,encoding='utf-8-sig',float_format='%.4f')
base=x.groupby('期间')[[Y,Z]].agg(['size','sum'])
def outcome(period,target):
    q=x if period=='全部' else x[x['期间']==period]
    return f"{int(q[target].sum())}/{len(q)}（{100*q[target].mean():.1f}%）"
def pair(feat,period):
    q=g[(g['特征']==feat)&(g['期间']==period)].iloc[0]
    return f"{int(q['成立时D2跌停数'])}/{int(q['特征成立笔数'])}（{q['成立时D2跌停率_pct']:.1f}%）",f"{int(q['对照D2跌停数'])}/{int(q['对照笔数'])}（{q['对照D2跌停率_pct']:.1f}%）"
def hrow(feat):
    cells=[feat]
    for period in ['2022-24','2025','2026']:
        cells.extend(pair(feat,period))
    return '| '+' | '.join(cells)+' |'
