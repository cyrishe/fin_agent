def minutes():
 configure();demand=pd.read_pickle(OUT/'minute_demand.pkl');previous=pd.read_pickle(PREV/'minute_facts.pkl')
 rows=[];jobs=list(demand.groupby('d1_date'));OUT.joinpath('minute_days').mkdir(exist_ok=True)
 def day_job(day,g):
  cache=OUT/'minute_days'/f'{day}.json'
  if cache.exists():
   result=json.loads(cache.read_text())
   if {r['symbol'] for r in result}==set(g.symbol):return result
  reusable=previous[previous.d1_date.eq(day)&previous.symbol.isin(g.symbol)&previous.early_valid.eq(True)]
  missing=g[~g.symbol.isin(reusable.symbol)]
  if cache.exists():cache.unlink() # Only partial cache generated by this helper; refill missing demand.
  new=old.scan_day(day,missing) if len(missing) else []
  result=reusable.to_dict('records')+new
  cache.write_text(json.dumps(result,ensure_ascii=False,indent=2,allow_nan=True)+'\n')
  return result
 with ThreadPoolExecutor(max_workers=3) as pool:
  fs=[pool.submit(day_job,d,g) for d,g in jobs]
  for i,f in enumerate(as_completed(fs),1):
   rows+=f.result()
   if i%25==0:print('minutes',i,'/',len(jobs),flush=True)
 # R15 performs the same enrichment against these now-complete day caches.
 old.minutes()

