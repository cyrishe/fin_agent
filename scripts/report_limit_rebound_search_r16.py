def json_parameters(v):
 if isinstance(v,dict):return {k:json_parameters(x) for k,x in v.items()}
 if isinstance(v,(tuple,list)):return [json_parameters(x) for x in v]
 if isinstance(v,(float,np.floating)) and not np.isfinite(v):return str(v)
 return v

def simple_top_metrics(frame,probabilities):
 """The same ranking/hit counts, without unused AP and wide-frame copies."""
 cols=['symbol','d0_date','activated','observed_3','label_3']
 f=frame[cols].assign(score=np.asarray(probabilities))
 f=f.sort_values(['d0_date','score','symbol'],ascending=[True,False,True])
 f['rank']=f.groupby('d0_date').cumcount()+1;f['month']=f.d0_date.str[:7]
 months=sorted(f.month.unique());known=f[f.activated&f.observed_3]
 rates={};monthly=[]
 for k in (3,5):
  q=known[known['rank'].le(k)];rates[k]=float(q.label_3.mean()) if len(q) else None
  monthly.append(q.groupby('month').label_3.mean().reindex(months).fillna(0).to_numpy())
 return rates,np.mean(monthly,axis=0)

